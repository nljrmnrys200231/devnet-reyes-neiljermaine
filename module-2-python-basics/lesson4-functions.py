#Lesson 4: Functions

#What is function? a function is a reusable block of code designed top perform a specific operation, typically based on inputs called "parameters" and returning an output

#Parameter - In Python, a parameter is a variable name listed inside the parentheses of a function definition. It acts as a placeholder for a value that will be passed to the function. An argument is the actual value that is sent to the function when it is called.

#Argument -In Python, an argument is a value or object that you pass into a function or method when you call it. Arguments allow you to provide input data to the function so that it can perform its task.

#Return Values - When a function returns a value, it's providing a piece of data back to the caller.
